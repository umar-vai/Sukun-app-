"""Export the preview seed database into a Dart source file.

Usage: python3 export_seed.py <psql connection args...>

Reads every public table plus foreign keys and column defaults from a local
Postgres that has the repository migrations and preview_seed.sql applied, and
writes app/lib/preview/preview_seed_data.g.dart for the mock backend.
"""

import json
import pathlib
import subprocess
import sys

CONN = sys.argv[1:] or ["-h", "/tmp", "-p", "5433", "-U", "postgres", "-d", "seedtest"]
OUT = pathlib.Path(__file__).resolve().parents[2] / "lib" / "preview" / "preview_seed_data.g.dart"


def query(sql):
    out = subprocess.check_output(["psql", *CONN, "-At", "-c", sql], text=True)
    return json.loads(out.strip() or "null")


tables = query(
    "select json_agg(table_name order by table_name) from information_schema.tables "
    "where table_schema='public' and table_type='BASE TABLE'"
)
data = {}
for table in tables:
    rows = query(f'select coalesce(json_agg(t), \'[]\') from public."{table}" t')
    data[table] = rows

fks = query(
    "select json_agg(json_build_object('table', c.conrelid::regclass::text, "
    "'columns', (select json_agg(a.attname order by k.n) from unnest(c.conkey) with ordinality k(num, n) "
    "join pg_attribute a on a.attrelid = c.conrelid and a.attnum = k.num), "
    "'refTable', c.confrelid::regclass::text, "
    "'refColumns', (select json_agg(a.attname order by k.n) from unnest(c.confkey) with ordinality k(num, n) "
    "join pg_attribute a on a.attrelid = c.confrelid and a.attnum = k.num))) "
    "from pg_constraint c where c.contype = 'f' and c.connamespace = 'public'::regnamespace "
    "and c.confrelid::regclass::text not like 'auth.%'"
)

columns = query(
    "select json_object_agg(table_name, cols) from (select table_name, "
    "json_agg(json_build_object('name', column_name, 'default', column_default, 'nullable', is_nullable = 'YES') "
    "order by ordinal_position) cols from information_schema.columns where table_schema = 'public' "
    "group by table_name) s"
)

payload = json.dumps({"tables": data, "foreignKeys": fks, "columns": columns}, ensure_ascii=False)
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text(
    "// GENERATED by tool/preview/export_seed.py. Preview-only sample data.\n"
    "// ignore_for_file: lines_longer_than_80_chars\n\n"
    "const String previewSeedJson = r'''" + payload + "''';\n",
    encoding="utf-8",
)
print(f"wrote {OUT} ({len(payload)} bytes, {len(tables)} tables, {len(fks)} foreign keys)")
